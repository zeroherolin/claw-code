async function qt(e, t = (r) => console.error(r)) {
  if (e.poolSecretFile) return (await Tl(ut(e.poolSecretFile, { encoding: "utf-8" }), mt, `environment-secret read from ${e.poolSecretFile}`)).trim();
  let r = process.env.SELF_HOSTED_RUNNER_ENVIRONMENT_SECRET;
  if (r) return r.trim();
  let n = process.env.SELF_HOSTED_RUNNER_POOL_SECRET;
  if (n) return t("[runner:warn] SELF_HOSTED_RUNNER_POOL_SECRET is deprecated; use SELF_HOSTED_RUNNER_ENVIRONMENT_SECRET"), n.trim();
  throw Error("No environment secret provided. Use --environment-secret-file or set SELF_HOSTED_RUNNER_ENVIRONMENT_SECRET.");
}
